"""
export_weights.py - Serialize a policy's parameters to the VisibleSim weight file.

Generated by utilities/rlAppGenerator. The format is compact, self-describing
and integrity-checked, so a future C++ deploy path can load it without guessing
shapes. This is the *contract* between Python and C++ -- keep it stable even if
you switch ML frameworks (just make your exporter walk that framework's params
and call write_weights with a name->ndarray dict).

On-disk layout (all integers little-endian uint32, all data little-endian float32,
row-major):

    magic      : 4 bytes  b"VSW1"
    version    : uint32   (= 1)
    n_tensors  : uint32
    repeated n_tensors times:
        name_len : uint32
        name     : name_len bytes (UTF-8)
        ndim     : uint32
        dims     : ndim * uint32
        data     : prod(dims) * float32
    crc32      : uint32   (zlib.crc32 / IEEE 802.3 over every preceding byte)
"""

import struct
import zlib

import numpy as np

MAGIC = b"VSW1"
VERSION = 1


def write_weights(named_arrays, path):
    """named_arrays: dict[str, np.ndarray]  ->  writes `path`."""
    body = bytearray()
    body += MAGIC
    body += struct.pack("<I", VERSION)
    body += struct.pack("<I", len(named_arrays))
    for name, arr in named_arrays.items():
        a = np.ascontiguousarray(arr, dtype="<f4")
        nb = name.encode("utf-8")
        body += struct.pack("<I", len(nb))
        body += nb
        body += struct.pack("<I", a.ndim)
        for d in a.shape:
            body += struct.pack("<I", int(d))
        body += a.tobytes(order="C")
    crc = zlib.crc32(bytes(body)) & 0xFFFFFFFF
    body += struct.pack("<I", crc)
    with open(path, "wb") as f:
        f.write(body)
    return len(body)


def load_weights(path):
    """Read `path`, verify the CRC, and return dict[str, np.ndarray]."""
    with open(path, "rb") as f:
        blob = f.read()
    if len(blob) < 12 or blob[:4] != MAGIC:
        raise ValueError("bad magic / truncated file: %s" % path)
    stored_crc = struct.unpack("<I", blob[-4:])[0]
    if (zlib.crc32(blob[:-4]) & 0xFFFFFFFF) != stored_crc:
        raise ValueError("CRC mismatch (corrupt weight file): %s" % path)

    off = 4
    version, = struct.unpack_from("<I", blob, off); off += 4
    if version != VERSION:
        raise ValueError("unsupported version %d (expected %d)" % (version, VERSION))
    n_tensors, = struct.unpack_from("<I", blob, off); off += 4

    out = {}
    for _ in range(n_tensors):
        name_len, = struct.unpack_from("<I", blob, off); off += 4
        name = blob[off:off + name_len].decode("utf-8"); off += name_len
        ndim, = struct.unpack_from("<I", blob, off); off += 4
        dims = struct.unpack_from("<%dI" % ndim, blob, off); off += 4 * ndim
        count = int(np.prod(dims)) if ndim else 1
        data = np.frombuffer(blob, dtype="<f4", count=count, offset=off).copy()
        off += 4 * count
        out[name] = data.reshape(dims) if ndim else data
    return out


if __name__ == "__main__":
    # Round-trip self-test (no simulator needed): export then re-load + verify.
    from model import MLPPolicy

    policy = MLPPolicy(in_dim=5, hidden=8, n_actions=7, seed=1)
    path = "weights.bin"
    n = write_weights(policy.parameters(), path)
    print("wrote %s (%d bytes)" % (path, n))

    loaded = load_weights(path)
    for k, v in policy.parameters().items():
        assert np.allclose(v, loaded[k]), "mismatch in %s" % k
    print("round-trip + CRC check OK:", {k: v.shape for k, v in loaded.items()})
