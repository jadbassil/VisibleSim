"""
model.py - A tiny NumPy MLP policy for the <<appName>> environment.

Generated by utilities/rlAppGenerator. One shared per-block policy maps a
block's feature vector to logits over actions (col 0 = stay, col k = move to the
(k-1)-th legal destination). This is deliberately minimal -- a starting point,
not a tuned algorithm. To use PyTorch/JAX instead, replace this file with your
own policy and keep export_weights.py writing the same on-disk layout.
"""

import numpy as np


def _softmax(z, axis=-1):
    z = z - np.max(z, axis=axis, keepdims=True)
    e = np.exp(z)
    return e / np.sum(e, axis=axis, keepdims=True)


class MLPPolicy:
    def __init__(self, in_dim, hidden=32, n_actions=7, seed=0):
        rng = np.random.default_rng(seed)
        self.in_dim = in_dim
        self.hidden = hidden
        self.n_actions = n_actions
        # He-ish initialization.
        self.params = {
            "W1": (rng.standard_normal((hidden, in_dim)) * (1.0 / np.sqrt(in_dim))).astype(np.float32),
            "b1": np.zeros(hidden, dtype=np.float32),
            "W2": (rng.standard_normal((n_actions, hidden)) * (1.0 / np.sqrt(hidden))).astype(np.float32),
            "b2": np.zeros(n_actions, dtype=np.float32),
        }

    # -- forward -----------------------------------------------------------
    def forward(self, x):
        """x: (N, in_dim) -> logits: (N, n_actions). Also returns the hidden act."""
        h = np.maximum(0.0, x @ self.params["W1"].T + self.params["b1"])
        logits = h @ self.params["W2"].T + self.params["b2"]
        return logits, h

    def policy(self, x, masks):
        """Masked action probabilities, shape (N, n_actions)."""
        logits, _ = self.forward(x)
        a = masks.shape[1]
        logits = logits[:, :a]
        neg_inf = np.where(masks > 0, 0.0, -1e9).astype(np.float32)
        return _softmax(logits + neg_inf, axis=-1)

    def act(self, x, masks, rng=None, greedy=False):
        """Sample (or argmax) an action per block. Returns (actions, logp)."""
        rng = rng or np.random.default_rng()
        probs = self.policy(x, masks)
        n = probs.shape[0]
        actions = np.zeros(n, dtype=np.int64)
        logp = np.zeros(n, dtype=np.float32)
        for i in range(n):
            if greedy:
                a = int(np.argmax(probs[i]))
            else:
                a = int(rng.choice(probs.shape[1], p=probs[i]))
            actions[i] = a
            logp[i] = np.log(probs[i, a] + 1e-8)
        return actions, logp

    # -- parameter access (used by export_weights.py) ----------------------
    def parameters(self):
        """Ordered name->array dict of trainable tensors."""
        return {k: self.params[k] for k in ("W1", "b1", "W2", "b2")}

    def set_parameters(self, named):
        for k, v in named.items():
            self.params[k] = np.asarray(v, dtype=np.float32)
