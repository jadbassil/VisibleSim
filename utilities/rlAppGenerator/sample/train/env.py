    # Smoke test: connect, run a few random steps, print shapes.
    with VisibleSimEnv() as env:
        obs = env.reset()
        print("connected; %d blocks, grid %s"
              % (len(obs["blocks"]), obs["grid_size"]))
        for t in range(5):
            arr = VisibleSimEnv.obs_to_arrays(obs)
            actions = {int(i): 0 for i in arr["ids"]}  # all "stay"
            obs, reward, done, _ = env.step(actions)
            print("step %d  reward=%.3f  done=%s" % (obs["step"], reward, done))
            if done:
                break
        print("smoke test OK")
