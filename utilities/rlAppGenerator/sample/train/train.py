"""
train.py - Minimal REINFORCE-style training loop for the <<appName>> env.

Generated by utilities/rlAppGenerator. This wires env.py + model.py together and
periodically exports weights. With the default block code (no legal moves and a
zero reward) it does not learn anything meaningful -- it exists to prove the
end-to-end loop runs. Implement getAvailableMoves()/applyAction()/computeReward()
in the C++ block code, then flesh out the update below into real PPO/REINFORCE.
"""

import argparse

import numpy as np

from env import VisibleSimEnv
from model import MLPPolicy
from export_weights import write_weights


def run_episode(env, policy, rng):
    """Roll out one episode. Returns the trajectory and the total reward."""
    obs = env.reset()
    traj = []  # (features, masks, actions, reward)
    total = 0.0
    done = False
    while not done:
        arr = VisibleSimEnv.obs_to_arrays(obs)
        # Pad/clip masks to the policy's action dimension.
        masks = np.zeros((arr["x"].shape[0], policy.n_actions), dtype=np.float32)
        a = min(masks.shape[1], arr["masks"].shape[1])
        masks[:, :a] = arr["masks"][:, :a]
        actions, _logp = policy.act(arr["x"], masks, rng=rng)
        amap = {int(i): int(actions[k]) for k, i in enumerate(arr["ids"])}
        obs, reward, done, _ = env.step(amap)
        traj.append((arr["x"], masks, actions, reward))
        total += reward
    return traj, total


def reinforce_update(policy, traj, lr=1e-2, gamma=0.99):
    """One vanilla policy-gradient step over a single episode (placeholder)."""
    rewards = [r for *_unused, r in traj]
    # Discounted returns (broadcast the per-step scalar reward to every block).
    returns, g = [], 0.0
    for r in reversed(rewards):
        g = r + gamma * g
        returns.append(g)
    returns.reverse()
    ret = np.array(returns, dtype=np.float32)
    if ret.std() > 1e-6:
        ret = (ret - ret.mean()) / (ret.std() + 1e-8)

    # Gradient of sum_t return_t * log pi(a_t|s_t), accumulated over blocks.
    grads = {k: np.zeros_like(v) for k, v in policy.parameters().items()}
    for t, (x, masks, actions, _r) in enumerate(traj):
        probs = policy.policy(x, masks)         # (N, A)
        _, h = policy.forward(x)                 # (N, H)
        onehot = np.zeros_like(probs)
        onehot[np.arange(len(actions)), actions] = 1.0
        dlogits = (onehot - probs) * ret[t]      # (N, A)
        grads["W2"] += dlogits.T @ h
        grads["b2"] += dlogits.sum(axis=0)
        dh = (dlogits @ policy.params["W2"]) * (h > 0)
        grads["W1"] += dh.T @ x
        grads["b1"] += dh.sum(axis=0)

    for k in policy.params:
        policy.params[k] += lr * grads[k].astype(np.float32)


def main():
    ap = argparse.ArgumentParser(description="Train a policy on the <<appName>> env.")
    ap.add_argument("--episodes", type=int, default=10)
    ap.add_argument("--render", action="store_true")
    ap.add_argument("--export-every", type=int, default=5)
    ap.add_argument("--out", type=str, default="weights.bin")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    rng = np.random.default_rng(args.seed)
    with VisibleSimEnv(render=args.render) as env:
        # Size the policy from the first observation's feature width.
        in_dim = VisibleSimEnv.obs_to_arrays(env.reset())["x"].shape[1]
        policy = MLPPolicy(in_dim=in_dim, hidden=32, n_actions=7, seed=args.seed)

        for ep in range(args.episodes):
            traj, total = run_episode(env, policy, rng)
            reinforce_update(policy, traj)
            print("episode %d  steps=%d  return=%.3f" % (ep, len(traj), total))
            if (ep + 1) % args.export_every == 0:
                n = write_weights(policy.parameters(), args.out)
                print("  exported %s (%d bytes)" % (args.out, n))

        write_weights(policy.parameters(), args.out)
        print("final weights -> %s" % args.out)


if __name__ == "__main__":
    main()
